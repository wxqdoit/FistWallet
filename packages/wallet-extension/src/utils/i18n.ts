export type TranslationKey = keyof typeof translations.en;

export const t = (language: LanguageCode, key: TranslationKey, params?: TranslationParams): string => {
    const template = translations[language]?.[key] ?? translations.en[key];
    if (!params) {
        return template;
    }
    return template.replace(/\{\{(\w+)\}\}/g, (_, name) => String(params[name] ?? ''));
};

export const formatLocalizedDateTime = (timestamp: number | string | Date, language: LanguageCode): string => {
    const date = new Date(timestamp);
    if (isNaN(date.getTime())) return '';
    const localeMap: Record<LanguageCode, string> = {
        zh: 'zh-CN',
        en: 'en-US',
        ja: 'ja-JP',
        ko: 'ko-KR',
    };
    return date.toLocaleString(localeMap[language] || 'en-US', {
        year: 'numeric',
        month: 'numeric',
        day: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
    });
};
